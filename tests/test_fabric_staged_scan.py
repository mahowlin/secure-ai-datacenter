"""Exercise the actual documented staging block; no Terraform/APIC execution."""
from pathlib import Path
import os,re,subprocess,sys,tempfile,unittest
ROOT=Path(__file__).resolve().parents[1]
class StagedFabricScan(unittest.TestCase):
 def stage(self, parent):
  old=parent/'existing-project';(old/'data/example-tenant-b').mkdir(parents=True,exist_ok=True)
  (old/'data/example-tenant-b/example-tenant-b.yml').write_text('# Generated by render-aci.py\napic: {}\n')
  (old/'data/site-owned.yml').write_text('apic: {}\n')
  for folder in ['modules','defaults']:
   (old/folder).mkdir(exist_ok=True);(old/folder/'selection.yml').write_text('apic: {}\n')
  doc=(ROOT/'agents/fabric.md').read_text().split('## Dedicated generated scan root',1)[1]
  block=re.search(r'```bash\n(.*?)```',doc,re.S).group(1)
  env={**os.environ,'PLATFORM_ROOT':str(ROOT),'PLATFORM_PYTHON':sys.executable,'FABRIC_ROOT':str(old)}
  result=subprocess.run(['bash','-euc',block+'\nprintf "\\nSTAGE=%s\\n" "$FABRIC_STAGE"'],env=env,text=True,capture_output=True)
  self.assertEqual(result.returncode,0,result.stderr)
  stage=Path(result.stdout.rsplit('STAGE=',1)[1].strip());self.addCleanup(__import__('shutil').rmtree,stage)
  return old,stage
 def test_renamed_generated_identity_cannot_enter_new_scan_and_site_data_survives(self):
  with tempfile.TemporaryDirectory() as tmp:
   old,stage=self.stage(Path(tmp))
   self.assertTrue((old/'data/example-tenant-b/example-tenant-b.yml').exists())
   self.assertTrue((old/'data/site-owned.yml').exists())
   self.assertFalse((stage/'data/example-tenant-b').exists())
   self.assertFalse((stage/'data/site-owned.yml').exists())
   self.assertTrue((stage/'data/tenant-workloads/tenant-workloads.yml').exists())
 def test_extra_old_identity_fails_exact_scan_check(self):
  with tempfile.TemporaryDirectory() as tmp:
   _,stage=self.stage(Path(tmp));extra=stage/'data/removed-tenant.yml';extra.write_text('apic: {}\n')
   result=subprocess.run([sys.executable,str(ROOT/'scripts/verify-artifact-manifest.py'),'--manifest',str(ROOT/'generated/artifact-manifest.yaml'),'--repo','secure-ai-fabric','--target-root',str(stage),'--fail-on-extra'],text=True,capture_output=True)
   self.assertNotEqual(result.returncode,0)
if __name__=='__main__':unittest.main()
