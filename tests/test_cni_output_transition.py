"""Conditional raw-install output ownership: no endpoint or runtime effects."""
import importlib.util
from pathlib import Path
import sys
import tempfile
import unittest
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))

def load(name, file):
    spec = importlib.util.spec_from_file_location(name, ROOT / 'scripts' / file)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module
renderer = load('cni_writer', 'render-ocp.py')
verifier = load('cni_verifier', 'verify-artifact-manifest.py')

class CNITransition(unittest.TestCase):

    def test_cilium_ovn_cilium_matches_fresh_and_preserves_independent_file(self):
        common = {
            'install-config.yaml': 'networking: {}\n',
            'metadata.yaml': 'networkType: OVNKubernetes\n'}
        cilium = {
            **common,
            'manifests/ciliumconfig.yaml': '# Generated by render-ocp.py\nkind: CiliumConfig\n',
            'manifests/cluster-network-02-config-local.yml': '# Generated by render-ocp.py\nkind: Network\n'}
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / 'out'
            fresh = Path(tmp) / 'fresh'
            renderer.write_ocp_outputs(out, cilium)
            foreign = out / 'site-owned.txt'
            foreign.write_bytes(b'keep')
            renderer.write_ocp_outputs(out, common)
            self.assertFalse((out / 'manifests/ciliumconfig.yaml').exists())
            self.assertFalse((out / 'manifests/cluster-network-02-config-local.yml').exists())
            self.assertEqual(foreign.read_bytes(), b'keep')
            renderer.write_ocp_outputs(out, cilium)
            renderer.write_ocp_outputs(fresh, cilium)
            for relative in cilium:
                self.assertEqual((out / relative).read_bytes(), (fresh / relative).read_bytes())

    def test_foreign_cni_path_is_not_deleted(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp)
            p = out / 'manifests/ciliumconfig.yaml'
            p.parent.mkdir()
            p.write_text('independent')
            with self.assertRaisesRegex(ValueError, 'another owner'):
                renderer.write_ocp_outputs(out, {'metadata.yaml': 'networkType: OVNKubernetes'})
            self.assertEqual(p.read_text(), 'independent')

    def test_verifier_rejects_self_consistent_but_forbidden_cilium_for_ovn(self):
        for path, document in [
            (
                'manifests/ciliumconfig.yaml',
                {
                    'kind': 'CiliumConfig',
                    'spec': {
                        'version': 'x',
                        'image': {
                            'cilium': 'x'}}}),
            (
                'manifests/cluster-network-02-config-local.yml',
                {
                    'apiVersion': 'operator.openshift.io/v1',
                    'kind': 'Network',
                    'metadata': {
                        'name': 'cluster'},
                    'spec': {
                        'networkType': 'Cilium',
                        'deployKubeProxy': False}})]:
            errors = verifier.stale_ocp_errors(Path(path), document, 'OVNKubernetes')
            self.assertTrue(any(('forbidden Cilium' in e for e in errors)), errors)
if __name__ == '__main__':
    unittest.main()
