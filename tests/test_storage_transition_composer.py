from __future__ import annotations

import importlib.util
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

ATTESTATION = SCRIPTS / "scoped-publication-attestation.py"
SPEC = importlib.util.spec_from_file_location("scoped_publication_attestation", ATTESTATION)
MODULE = importlib.util.module_from_spec(SPEC)
assert SPEC.loader is not None
SPEC.loader.exec_module(MODULE)

from storage_transition_composer import compose_root, compose_root_bytes


class StorageTransitionComposerTests(unittest.TestCase):
    def base(self) -> dict:
        return {
            "apiVersion": "kustomize.config.k8s.io/v1beta1",
            "kind": "Kustomization",
            "resources": ["../_types/hcp-management", "../foundation/storage/lvms-retained", "network.yaml"],
            "patches": [
                {"target": {"kind": "Application", "name": "cilium-config"}, "patch": "network"},
                {"target": {"kind": "Application", "name": "lvms-operator"}, "patch": "storage"},
                {"target": {"kind": "Application", "name": "hubble-timescape"}, "patch": "timescape"},
            ],
        }

    def git(self, root: Path, *args: str) -> str:
        return subprocess.check_output(["git", "-C", str(root), *args], text=True).strip()

    def commit(self, root: Path, message: str) -> str:
        self.git(root, "add", ".")
        self.git(root, "-c", "user.name=SAIF Test", "-c", "user.email=saif@example.invalid",
                 "commit", "-m", message)
        return self.git(root, "rev-parse", "HEAD")

    def test_both_stages_preserve_non_storage_owners(self) -> None:
        base = self.base()
        held = compose_root(base, "consumer-hold")
        self.assertEqual(held["resources"], [
            "../_types/hcp-management",
            "../_staged/storage/lvms-default-hold/example-management",
            "network.yaml",
        ])
        self.assertEqual(held["patches"][0], base["patches"][0])
        self.assertNotIn("lvms-operator", yaml.safe_dump(held))
        self.assertIn("$patch: delete", held["patches"][-1]["patch"])

        cutover = compose_root(held, "provider-cutover")
        self.assertEqual(cutover["resources"], [
            "../_types/hcp-management", "storage-portworx.yaml", "network.yaml",
        ])
        self.assertEqual(cutover["patches"][0], base["patches"][0])

    def test_attestation_binds_exact_composed_root_and_canonical_divergence(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            target = root / "target"
            target.mkdir()
            self.git(target, "init", "-q")
            path = target / "clusters/example-management/kustomization.yaml"
            path.parent.mkdir(parents=True)
            base_bytes = ("# Generated by render-gitops.py — do not edit manually.\n---\n" +
                          yaml.safe_dump(self.base(), sort_keys=False)).encode()
            path.write_bytes(base_bytes)
            base = self.commit(target, "base")
            path.write_bytes(compose_root_bytes(base_bytes, "consumer-hold"))
            head = self.commit(target, "hold")
            # Worktree content must not replace the exact composed commit.
            path.write_bytes(b"uncommitted unrelated worktree contents\n")

            manifest = root / "manifest.yaml"
            manifest.write_text(yaml.safe_dump({
                "source": {"commit": "1" * 40},
                "targets": [{"repo": "saif-gitops", "files": [{
                    "path": "clusters/example-management/kustomization.yaml", "sha256": "2" * 64,
                }]}],
            }))
            stages = root / "stages.yaml"
            stages.write_text(yaml.safe_dump({"spec": {
                "targetRepo": "saif-gitops", "targetBase": base,
                "stages": [{"name": "hold", "order": 1, "allowlist": [{
                    "path": "clusters/example-management/kustomization.yaml",
                    "state": "composed", "activation": "consumer-hold",
                }]}],
            }}))
            attestation = MODULE.build_attestation(manifest, stages, "hold", target, base, head)
            entry = attestation["scope"]["orderedAllowlist"][0]
            self.assertTrue(entry["preservesNonStorageOwners"])
            self.assertEqual(entry["canonicalSha256"], "2" * 64)
            self.assertEqual(entry["baseSha256"], MODULE.sha256_bytes(base_bytes))


if __name__ == "__main__":
    unittest.main()
