"""Executable joins between machine bootstrap, physical fabric and tenant BGP."""
import importlib.util
from pathlib import Path
import sys,tempfile,unittest,copy
import yaml
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'scripts'))
from resolver import resolve
spec=importlib.util.spec_from_file_location('aci',ROOT/'scripts/render-aci.py');aci=importlib.util.module_from_spec(spec);spec.loader.exec_module(aci)
class ManagementHandoff(unittest.TestCase):
 def test_gateway_vlan_hosts_and_routed_tenant_are_distinct(self):
  platform=resolve(ROOT);out=aci.render(platform,ROOT);cluster=next(c for c in platform.clusters if c.name=='example-management');network=cluster.machine_network
  m=yaml.safe_load(out['platform-management/platform-management.yml'])['apic'];self.assertNotIn('access_policies',m);tenant=m['tenants'][0];bd=tenant['bridge_domains'][0];epg=tenant['application_profiles'][0]['endpoint_groups'][0]
  self.assertEqual(bd['subnets'][0]['ip'],network.gateway+'/24');self.assertEqual({p['vlan'] for p in epg['static_ports']},{network.vlan});self.assertEqual({p['node_id'] for p in epg['static_ports']},{103,104})
  self.assertNotIn('l3outs',tenant);self.assertEqual(bd['l3outs'],[network.aci_attachment['siteL3Out']]);self.assertEqual(cluster.management_interface.mode,'active-backup')
  self.assertEqual(cluster.parent_networking.tenant_members,['eth2','eth3']);self.assertTrue(any('tenant-workloads' in p for p in out));self.assertFalse(any('Tenant-B' in p or 'n5k' in text for p,text in out.items()))
 def test_renamed_subject_removes_only_owned_stale_files(self):
  with tempfile.TemporaryDirectory() as tmp:
   p=Path(tmp);old=p/'Tenant-B/Tenant-B.yml';old.parent.mkdir();old.write_text('# Generated by render-aci.py\nold')
   foreign=p/'site-owned.yml';foreign.write_text('apic: {}\n');aci.write_outputs(p,{'tenant-workloads/current.yml':'# Generated by render-aci.py\nnew'})
   self.assertFalse(old.exists());self.assertTrue(foreign.exists())
 def test_varied_management_input_drives_subnet_and_attachment(self):
  platform=resolve(ROOT);cluster=next(c for c in platform.clusters if c.name=='example-management');n=cluster.machine_network;n.vlan=2201;n.cidr='203.0.113.0/24';n.gateway='203.0.113.1';n.aci_attachment['serverPorts'][0]['port']=21
  text=aci.render(platform,ROOT)['platform-management/platform-management.yml'];self.assertIn('203.0.113.1/24',text);self.assertIn('vlan: 2201',text);self.assertIn('port: 21',text);self.assertNotIn('198.18.1.1/24',text)
 def test_install_and_day2_mtu_follow_declared_networks(self):
  from gitops_renderer.management import _render_prerequisites_nmstate
  platform=resolve(ROOT);cluster=next(c for c in platform.clusters if c.name=='example-management');cluster.kube_api_networks[0].mtu=1450
  files=_render_prerequisites_nmstate(cluster,'bond1',platform.defaults)
  values=[yaml.safe_load(v) for v in files.values()]
  interfaces=[i for v in values for i in v['spec']['desiredState']['interfaces']]
  self.assertTrue(any(i.get('mtu')==1450 and i['name'].startswith('bond1.') for i in interfaces))
 def test_unknown_owner_and_lacp_do_not_silently_render(self):
  platform=resolve(ROOT);cluster=next(c for c in platform.clusters if c.name=='example-management');cluster.machine_network.aci_attachment['cluster']='missing'
  with self.assertRaisesRegex(ValueError,'unknown cluster'):aci.render(platform,ROOT)
  cluster.machine_network.aci_attachment['cluster']=cluster.name;cluster.management_interface.mode='802.3ad'
  with self.assertRaisesRegex(ValueError,'active-backup'):aci.render(platform,ROOT)
 def test_unspecified_mtu_is_not_an_injected_renderer_policy(self):
  platform=resolve(ROOT);network=next(c for c in platform.clusters if c.name=="example-third-party").machine_network;self.assertIsNone(network.mtu)
 def test_colliding_physical_port_fails(self):
  platform=resolve(ROOT);cluster=next(c for c in platform.clusters if c.name=='example-management');cluster.machine_network.aci_attachment['serverPorts'].append(copy.deepcopy(cluster.machine_network.aci_attachment['serverPorts'][0]))
  with self.assertRaisesRegex(ValueError,'duplicate'):aci.render(platform,ROOT)

 def test_separate_shared_access_keeps_physical_and_domain_joins(self):
  platform=resolve(ROOT);out=aci.render(platform,ROOT)
  self.assertEqual(len(out),5)
  domains=yaml.safe_load(out['access/10-platform-management-domains.yml'])['apic']
  attachments=yaml.safe_load(out['access/30-platform-management-attachments.yml'])['apic']
  self.assertNotIn('tenants',domains);self.assertNotIn('tenants',attachments)
  d=domains['access_policies'];a=attachments['access_policies']
  self.assertEqual(d['physical_domains'][0]['vlan_pool'],d['vlan_pools'][0]['name'])
  self.assertEqual(d['aaeps'][0]['physical_domains'],[d['physical_domains'][0]['name']])
  groups={p['name']:p['aaep'] for p in a['leaf_interface_policy_groups']}
  self.assertEqual(set(groups.values()),{'platform-management-aaep',platform.fabric.aci.ai_pod_aaep})
  selectors=[sel for profile in a['leaf_interface_profiles'] for sel in profile['selectors']]
  self.assertEqual(len(selectors),12)
  self.assertTrue(all(sel['policy_group'] in groups for sel in selectors))
  self.assertTrue(all('\n\n' not in text for text in out.values()))

if __name__=='__main__':unittest.main()
