"""Compose a storage-only hosted-control-plane root from an exact target baseline."""

from __future__ import annotations

import copy
from pathlib import Path

import yaml

from resolver import hosted_control_plane_name


HEADER = "# Generated by render-gitops.py — do not edit manually.\n"
LEGACY_LVMS = "../foundation/storage/lvms-retained"
HOLD_LVMS = "../_staged/storage/lvms-default-hold/" + hosted_control_plane_name(Path(__file__).resolve().parents[1])
PORTWORX = "storage-portworx.yaml"
STORAGE_RESOURCES = {LEGACY_LVMS, HOLD_LVMS, PORTWORX}
STORAGE_PATCH_OWNERS = {("Application", "lvms-operator"), ("Application", "hubble-timescape")}


def _patch_owner(patch: dict) -> tuple[str | None, str | None]:
    target = patch.get("target", {}) if isinstance(patch, dict) else {}
    return target.get("kind"), target.get("name")


def _non_storage_view(root: dict) -> dict:
    view = copy.deepcopy(root)
    view["resources"] = [item for item in view.get("resources", []) if item not in STORAGE_RESOURCES]
    view["patches"] = [
        item for item in view.get("patches", []) if _patch_owner(item) not in STORAGE_PATCH_OWNERS
    ]
    return view


def _timescape_delete_patch() -> dict:
    return {
        "target": {"kind": "Application", "name": "hubble-timescape"},
        "patch": "\n".join([
            "apiVersion: argoproj.io/v1alpha1",
            "kind: Application",
            "metadata:",
            "  name: hubble-timescape",
            "  namespace: openshift-gitops",
            "$patch: delete",
        ]),
    }


def compose_root(document: dict, activation: str) -> dict:
    if activation not in {"consumer-hold", "provider-cutover"}:
        raise ValueError(f"unsupported compact storage activation: {activation}")
    if document.get("kind") != "Kustomization":
        raise ValueError("compact storage composition requires a Kustomization root")

    result = copy.deepcopy(document)
    resources = list(result.get("resources", []))
    storage_indexes = [index for index, item in enumerate(resources) if item in STORAGE_RESOURCES]
    if len(storage_indexes) != 1:
        raise ValueError("target root must contain exactly one compact storage owner")
    storage_index = storage_indexes[0]
    current = resources[storage_index]
    if activation == "consumer-hold":
        if current != LEGACY_LVMS:
            raise ValueError("consumer hold must start from the retained LVMS owner")
        resources[storage_index] = HOLD_LVMS
    else:
        if current not in {LEGACY_LVMS, HOLD_LVMS}:
            raise ValueError("provider cutover must start from retained or held LVMS")
        resources[storage_index] = PORTWORX
    result["resources"] = resources

    patches = list(result.get("patches", []))
    lvms = [item for item in patches if _patch_owner(item) == ("Application", "lvms-operator")]
    timescape = [item for item in patches if _patch_owner(item) == ("Application", "hubble-timescape")]
    if len(lvms) > 1 or len(timescape) != 1:
        raise ValueError("target root has unexpected LVMS or Timescape patch ownership")
    result["patches"] = [
        item for item in patches if _patch_owner(item) not in STORAGE_PATCH_OWNERS
    ] + [_timescape_delete_patch()]

    if _non_storage_view(result) != _non_storage_view(document):
        raise ValueError("storage composition changed a non-storage root owner")
    expected = HOLD_LVMS if activation == "consumer-hold" else PORTWORX
    actual_storage = [item for item in result["resources"] if item in STORAGE_RESOURCES]
    if actual_storage != [expected]:
        raise ValueError("storage composition produced an unexpected root owner")
    return result


def compose_root_bytes(content: bytes, activation: str) -> bytes:
    result = compose_root(yaml.safe_load(content), activation)
    return (HEADER + yaml.dump(
        result, default_flow_style=False, sort_keys=False, explicit_start=True
    )).encode()


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-root", type=Path, required=True)
    parser.add_argument("--activation", choices=("consumer-hold", "provider-cutover"), required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(compose_root_bytes(args.base_root.read_bytes(), args.activation))
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
